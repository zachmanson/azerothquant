-- Written by the azerothquant Brain after every import; edits are overwritten.
-- lastImported[realm][faction] is when the latest of your own imported Scans in
-- that Market was requested. The Addon deletes stored Scans up to then.
-- lastMailboxRead[realm][character] is when the latest imported Mailbox Read of
-- that Character was taken. The Addon deletes stored Mailbox Reads up to then.
-- lastCharacterRead[realm][character] is the same for Character Reads.
-- recommendations[realm][faction] is that Market's Recommendations, in copper.
-- budget is the Budget the Brain sized them within (nil for all the gold), and each
-- shoppingList row is an option sized as if it were the only buy. stake is the gold
-- plus the own Listings up at cost, room what an option may cost and lossCap the
-- most Unsold Loss it may have under the risk caps (nil without them); a row they
-- shrank has capped, its units by the gold alone, and cappedBy, the cap that shrank
-- it ("room" or "loss"). A Flip to Sell or Flip to Vendor row has listings (bought),
-- posts (stacks posted) and days (until its last unit sells; nil on a Flip to
-- Vendor, which sells now). A
-- Flip to Craft's row (action Craft on the shoppingList) lists its reagent buys:
-- { itemKey, quantity, maxUnitPrice, merchant = true when bought from a merchant },
-- and its output's postAt (nil when none of it beats vendoring).
-- Every Craft row names its character, and lists the held reagents it uses as
-- uses = { { itemKey, quantity } }. One that can't be made says why as
-- blocked = { reason = "noData", itemKey } or { reason = "unknownBindType" }.
-- A Craft that crafts a short reagent first lists those Sub-crafts, deepest first,
-- as via = { { itemKey, crafts, character } }; uses and buys cover the whole chain.
-- Every Craft row has its Craft Chain as chain = { node }: its exits (sell or vendor),
-- the last with the craft as its one child, over the sources that feed it. A node is
-- { kind = "sell"|"vendor"|"craft"|"use"|"buy"|"merchant"|"leftover", itemKey,
-- quantity (the row's total), gold (signed; nil where unknown), children }. A craft
-- also has crafts and character, a sell postAt, cut, deposit and effort, a buy
-- maxUnitPrice and effort, and the node that blocks a row blocked. Every node's gold
-- but a craft's (the sum of its children's) adds up to the row's profit. A blocked
-- row's chain is one craft, as it would be sourced, with no exit.
-- A Holdings Sell or Vendor row whose units were bought on the Auction House has
-- paid (per unit), paidUnits (how many units that covers), roi (a share, after
-- the cut) and roiHint = true when it's a good time to sell (only a hint).
-- held[itemKey] says which Characters hold it, by name: { { character, bags, bank,
-- bound } }, where bound is the part of bags and bank that can't be mailed or sold.
-- buyUnder lists the Buy Unders, the most to pay per unit on the Auction House:
-- { itemKey, price, way = "Vendor"|"Sell"|"Craft", units (nil for no limit), seen
-- (Scans that saw a Listing at or under it), windowDays, listedNow = true when the
-- latest Scan did }, and a Craft way's recipe (recipeID), output (Item Key) and
-- crafter. A Disenchant way names its disenchanter and the expected mats of one
-- Disenchant as mats = { { itemKey, quantity } }. A Disenchant source group's entry
-- has no itemKey but group = { quality, class = "armor"|"weapon", minLevel, maxLevel }:
-- the most to pay for any item in it that can be Disenchanted.
-- A Flip to Disenchant's row (action Disenchant on the shoppingList, no itemKey) has
-- disenchant = { group, disenchanter, mats, buys = { { itemKey, price } } }: the
-- group it buys, as a Buy Under's, and the Listings it buys, cheapest first.
-- lootAlert is what a drop must be worth for a Loot Alert: { threshold (one unit),
-- items = { [itemKey] = { value, action = "Sell"|"Vendor"|"Disenchant"|"Craft" } } }:
-- each Item Key in the Scan whose one unit alone is worth at least the threshold.
-- disenchantExcluded is what can't be Disenchanted, whatever its group: itemIDs and
-- equipLocs, each a set.
-- postDurationHours is how long every post lasts (2, 8 or 24): the Brain charges
-- Deposits for that long, so the Addon's Post button posts for it too.
-- brain is the Brain's status: { version, problem (a line for the player, nil when
-- all is well) }. The shipped stub has none, which tells the Addon the Brain has
-- never run.
